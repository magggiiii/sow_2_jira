# the SAME class object.
from models.intelligence_schemas import EvaluationScores

__all__ = ["EvaluationScores", "HierarchicalJudge"]

# ─── Hierarchical Judge ───────────────────────────────────────────────────────

class HierarchicalJudge:
    """LLM-as-a-judge for comparing EPIC -> Tickets hierarchies."""

    def __init__(self, model_name: str = "ollama/llama3", base_url: Optional[str] = None):
        # langchain is an optional/heavy eval-only dependency; import lazily so
        # the module (and its re-exported EvaluationScores) stays importable even
        # when langchain is not installed. Only instantiating the judge needs it.
        from langchain.prompts import ChatPromptTemplate
        from langchain_openai import ChatOpenAI

        # Default to Admin Bifrost if not provided
        self.base_url = base_url or os.getenv("BIFROST_URL", "http://s2j-admin-bifrost:8081/v1")
        self.api_key = os.getenv("BIFROST_API_KEY", "bifrost-admin-key")

        self.llm = ChatOpenAI(
            model=model_name,
            openai_api_base=self.base_url,
            openai_api_key=self.api_key,
            temperature=0
        )
        
        self.prompt_template = ChatPromptTemplate.from_messages([
            (
                "system",
                # Implicit string concatenation keeps each source line <=100 chars
                # (ruff E501) while the rendered prompt text is byte-for-byte the
                # same as the original triple-quoted block.
                "You are an expert software engineer and QA analyst.\n"
                "Your task is to evaluate the quality of a 'Jira Extraction'"
                " from a Statement of Work (SOW).\n"
                "The extraction is hierarchical: EPIC -> Tickets (Stories).\n"
                "\n"
                "Compare the **Actual Output** (generated by the AI) against the"
                " **Expected Output** (Ground Truth).\n"
                "\n"
                "### Criteria:\n"
                "1. **Alignment**: Does the generated Epic title and description"
                " match the intent of the Ground Truth Epic?\n"
                "2. **Recall**: How many of the required Stories from the Ground"
                " Truth are present in the Actual Output? (Matches can be"
                " semantic).\n"
                "3. **Fidelity**: For the stories that match, how accurate are the"
                " details (description, ACs)?\n"
                "4. **Hallucination**: Does the Actual Output contain stories or"
                " requirements that are NOT in the Ground Truth or the SOW text?\n"
                "\n"
                "### Output Format:\n"
                "Return ONLY a valid JSON object with the following keys:\n"
                "- alignment: (0.0 to 1.0)\n"
                "- recall: (0.0 to 1.0)\n"
                "- fidelity: (0.0 to 1.0)\n"
                "- hallucination: (0.0 to 1.0)\n"
                "- reasoning: (string explaining the scores)\n",
            ),
            ("user", """### Source Text:
{source_text}

### Expected Output (Ground Truth):
{expected_output}

### Actual Output (Generated):
{actual_output}

Evaluate the extraction quality and return the JSON scores.""")
        ])

    def evaluate(
        self,
        source_text: str,
        expected_output: Dict[str, Any],
        actual_output: List[Dict[str, Any]],
    ) -> EvaluationScores:
        """
        Evaluate a single dataset item comparison.
        """
        formatted_expected = json.dumps(expected_output, indent=2)
        formatted_actual = json.dumps(actual_output, indent=2)
        
        messages = self.prompt_template.format_messages(
            source_text=source_text,
            expected_output=formatted_expected,
            actual_output=formatted_actual
        )
        
        # Invoke LLM directly for easier mocking
        response = self.llm.invoke(messages)
        
        try:
            content = response.content
            if hasattr(content, "decode"): # Handle bytes if necessary
                content = content.decode("utf-8")
            
            # Clean JSON if necessary
            if "```json" in content:
                content = content.split("```json")[1].split("```")[0].strip()
            elif "```" in content:
                content = content.split("```")[1].split("```")[0].strip()
            
            data = json.loads(content)
            return EvaluationScores(**data)
        except Exception as e:
            raw = getattr(response, "content", response)
            return EvaluationScores(
                alignment=0, recall=0, fidelity=0, hallucination=1.0,
                reasoning=f"Error parsing judge response: {str(e)}\nRaw: {raw}",
            )
